/**
 * Returns caption details for a category, falling back to English if the requested language is unavailable.
 */
export function getCategoryCaption(category, lang = 'en') {
  const item = categoryPhotos[category] || categoryPhotos.family;
  const langKey = item[lang] ? lang : 'en';
  const localized = item[langKey] || item.en;
  return {
    image: item.image,
    alt: item.alt,
    title: localized.title,
    text: localized.text,
  };
}

